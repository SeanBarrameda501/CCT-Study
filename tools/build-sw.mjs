// Writes sw.js with a precache list of every app file and a content hash as the cache version.
import fs from 'fs'; import path from 'path'; import crypto from 'crypto';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const walk = d => fs.readdirSync(path.join(ROOT, d), { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const core = ['index.html', 'manifest.webmanifest', ...walk('css'), ...walk('js'), ...walk('data'), ...walk('icons')];
const imgs = walk('images').filter(f => /\.(svg|png|jpe?g)$/i.test(f));
const hash = crypto.createHash('sha1'); for (const f of [...core, ...imgs]) hash.update(f).update(fs.readFileSync(path.join(ROOT, f)));
const version = hash.digest('hex').slice(0, 10);
const list = a => JSON.stringify(a.map(f => './' + f.split(path.sep).join('/')));
fs.writeFileSync(path.join(ROOT, 'sw.js'), `// Generated by tools/build-sw.mjs — do not edit by hand.
const VERSION = 'cct-${version}';
const CORE = ${list(core)};
const IMAGES = ${list(imgs)};
self.addEventListener('install', e => { e.waitUntil((async () => { const c = await caches.open(VERSION); await c.addAll(CORE); for (let i = 0; i < IMAGES.length; i += 40) await c.addAll(IMAGES.slice(i, i + 40)); await self.skipWaiting(); })()); });
self.addEventListener('activate', e => { e.waitUntil((async () => { for (const k of await caches.keys()) if (k !== VERSION) await caches.delete(k); await self.clients.claim(); })()); });
self.addEventListener('fetch', e => {
  const req = e.request; if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith((async () => {
    const c = await caches.open(VERSION);
    const hit = await c.match(req, { ignoreSearch: true }); if (hit) return hit;
    try { const res = await fetch(req); if (res.ok) c.put(req, res.clone()); return res; }
    catch (err) { if (req.mode === 'navigate') return (await c.match('./index.html')) || Response.error(); throw err; }
  })());
});
self.addEventListener('message', e => { if (e.data === 'recache') caches.open(VERSION).then(async c => { await c.addAll(CORE); for (let i = 0; i < IMAGES.length; i += 40) await c.addAll(IMAGES.slice(i, i + 40)); }); });
`);
console.log('sw.js', version, core.length, 'core files,', imgs.length, 'images');
